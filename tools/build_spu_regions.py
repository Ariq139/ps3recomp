#!/usr/bin/env python3
"""Lift inventoried raw SPURS regions and register immutable matching bytes.

Region lengths are upper bounds, not asserted runtime image sizes. Dispatch
checks the descriptor's whole image against these bytes before using a lift.
Existing exact-fingerprint registrations take precedence and can be skipped.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('inventory', type=Path)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--existing', type=Path, action='append', default=[])
    ap.add_argument('--job-abis', type=Path, help='Audited raw-region ABI metadata keyed by SHA-256')
    ap.add_argument('--first-id', type=lambda x: int(x, 0), default=0x6000)
    args = ap.parse_args()
    abi_path = args.job_abis or args.out.parent/'spu_job_abis.json'
    abis = json.loads(abi_path.read_text())['regions'] if abi_path.exists() else {}
    tools = Path(__file__).resolve().parent
    existing = set()
    for p in args.existing:
        existing.update(re.findall(r'spu_workload_register_img\(0x([0-9A-Fa-f]{16})ULL', p.read_text()))
    existing = {v.upper() for v in existing}
    rows = json.loads(args.inventory.read_text(encoding='utf-8'))['candidates']
    unique = {}
    for row in rows:
        if row['kind'] == 'raw-spurs' and row.get('region') and row.get('fingerprint') not in existing:
            unique.setdefault(row['region_sha256'], row)
    args.out.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by tools/build_spu_regions.py. Full submitted bytes must match. */',
             '#include "spu_workload.h"', 'extern void spu_begin_image(int);']
    registrations, manifest = [], []
    for index, (sha, row) in enumerate(unique.items()):
        ident = 'prescan_' + sha[:16]
        dest = args.out / ident
        dest.mkdir(parents=True, exist_ok=True)
        binary = Path(row['region'])
        funcs = dest / 'functions.json'
        log = dest / 'generation.log'
        with log.open('w', encoding='utf-8') as out:
            subprocess.run([sys.executable, str(tools/'find_spu_functions.py'), str(binary),
                            '--raw', '--out', str(funcs)], stdout=out, stderr=subprocess.STDOUT, check=True)
            subprocess.run([sys.executable, str(tools/'spu_lifter.py'), str(binary),
                            '--functions', str(funcs), '--output', str(dest),
                            '--symbol-prefix', ident], stdout=out, stderr=subprocess.STDOUT, check=True)
        for path in (dest/'spu_recomp.h', dest/'spu_recomp.c'):
            text = re.sub(r'#include "(?:\.\./)+runtime/spu/([^"/]+)"', r'#include "\1"', path.read_text())
            path.write_text(text, encoding='utf-8')
        data = binary.read_bytes()
        # Constants are separate includes to keep the registration file reviewable.
        inc = dest / 'image_bytes.inc'
        inc.write_text('\n'.join(','.join(f'0x{x:02x}' for x in data[i:i+16])+','
                                 for i in range(0, len(data), 16)), encoding='ascii')
        lines += [f'extern void {ident}_spu_func_00000000(spu_context*);',
                  f'extern void {ident}_spu_recomp_register(void);',
                  f'static const uint8_t {ident}_bytes[] = {{',
                  f'#include "{ident}/image_bytes.inc"', '};']
        image_id = args.first_id + index
        registrations += [f'    spu_begin_image({image_id});',
                          f'    {ident}_spu_recomp_register();',
                          f'    spu_workload_register_raw_region({ident}_bytes, sizeof({ident}_bytes),',
                          f'        {ident}_spu_func_00000000, {image_id}, "{ident}");']
        digest = hashlib.sha256(data).hexdigest()
        if digest != sha:
            raise ValueError(f'Region bytes changed since inventory: {binary}')
        tag = abis.get(digest, {}).get('context2_tag')
        if tag is not None and not 0 <= tag <= 31:
            raise ValueError(f'Invalid context tag for {digest}: {tag}')
        if tag is not None:
            registrations += [f'    spu_workload_set_raw_region_context2({image_id}, {tag}u);']
        manifest.append(dict(row, image_id=image_id, symbol_prefix=ident,
                             context2_tag=tag))
        print(f'Lifted {ident}: {len(data)} bounded bytes', flush=True)
    lines += ['__attribute__((constructor)) static void register_prescanned_spu_regions(void)', '{']
    lines += registrations + ['    spu_begin_image(0);', '}']
    (args.out/'spu_prescanned.c').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    (args.out/'spu_prescanned.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Prepared {len(manifest)} raw SPURS regions', flush=True)


if __name__ == '__main__':
    main()
